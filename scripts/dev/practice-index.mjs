#!/usr/bin/env node
/* Writes assets/js/kicau/practice/index.js: every problem's title by its key, so the Practice list needs no sheets.
   Run after any change to the practice templates:  node --no-warnings scripts/dev/practice-index.mjs */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const DIR = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../assets/js/kicau/practice');
const P = require(path.join(DIR, 'core.js'));
for (const f of P.FILES) if (fs.existsSync(path.join(DIR, f.file))) require(path.join(DIR, f.file));
const map = {};
for (const m of P.list()) map[m.key] = P.get(m.id).title;
const body = `/* Generated by scripts/dev/practice-index.mjs. Do not edit: problem titles by key, for the Practice list. */\n(function (g) { var P = g.KicauPractice; if (P && P.setTitles) P.setTitles(${JSON.stringify(map)}); })(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
fs.writeFileSync(path.join(DIR, 'index.js'), body);
console.log('Wrote', Object.keys(map).length, 'titles');
